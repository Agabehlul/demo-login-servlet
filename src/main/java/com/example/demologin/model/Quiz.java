package com.example.demologin.model;

public class Quiz {
    private String title;
    private int grade;

    public void setTitle(String title) {
        this.title = title;
    }

    public void setGrade(int grade) {
        this.grade = grade;
    }

    public String getTitle() {
        return title;
    }

    public int getGrade() {
        return grade;
    }
}
